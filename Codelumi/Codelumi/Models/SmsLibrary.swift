    /// 时间分散在过去约两天（i*53 分钟），约 1/4 标记已取，贴合真实使用画像。
    static func parsedRecords() -> [PickupRecord] {
        let parsed = PickupParser.parseAll(raw, ocrSource: false)
        var seen = Set<String>()
        var out: [PickupRecord] = []
        let now = Date()
        for (i, item) in parsed.enumerated() {
            let it = item.normalized
            let fp = it.kind.rawValue + "|" + it.value + "|" + it.address
            if !seen.insert(fp).inserted { continue }
            var record = PickupRecord(
                company: it.company,
                code: it.value,
                kind: it.kind,
                address: it.address,
                rawMessage: it.rawText,
                receivedAt: now.addingTimeInterval(-Double(i * 53 + 37) * 60),
                isPickedUp: false,
                courier: it.courier.isEmpty ? nil : it.courier,
                waybill: it.kind == .waybill ? nil : (it.waybill.isEmpty ? nil : it.waybill),
                tail: it.kind == .tail ? nil : (it.tail.isEmpty ? nil : it.tail),
                shelf: it.shelf.isEmpty ? nil : it.shelf,
                // 2026-10-27：快递柜格口也要落库，否则小组件"码后柜位"永远空
                locker: it.locker.isEmpty ? nil : it.locker
            )
            let pick = (out.count % 4 == 0)
            record.isPickedUp = pick
            if pick { record.pickedUpAt = record.receivedAt.addingTimeInterval(2 * 3600) }
            out.append(record)
        }
        return out
    }

